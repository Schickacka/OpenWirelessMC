static const size_t kParentDbCount = sizeof(kParentDb) / sizeof(kParentDb[0]);

const char *FindParentGameID(const char *child_id)
{
  if (!child_id || child_id[0] == '\0')
  {
    return NULL;
  }
  for (size_t i = 0; i < kParentDbCount; i++)
  {
    if (strcasecmp(child_id, kParentDb[i].child) == 0)
    {
      return kParentDb[i].parent;
    }
  }
  return NULL;
}
